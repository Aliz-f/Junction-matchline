/**
 * Provenance disclosure (FE-01).
 *
 * Every fact and AI output must disclose where it came from: synthetic data is
 * labelled `DEMO DATA`, scripted AI `DEMO AI` (AGENTS.md section 5). These
 * labels are not decorative and must never be suppressed to make a demo look
 * more convincing.
 */
import type { SourceKind } from "@/lib/api/types";
import { formatKickoff, machineDateTime } from "@/lib/time";

const SOURCE_LABEL: Record<SourceKind, string> = {
  DEMO_SYNTHETIC: "DEMO DATA",
  LIVE_PROVIDER: "Live provider",
};

const SOURCE_TITLE: Record<SourceKind, string> = {
  DEMO_SYNTHETIC: "Synthetic demo data. These fixtures, scores and events are invented, not real football results.",
  LIVE_PROVIDER: "Supplied by the configured football data provider.",
};

export function SourceBadge({ kind, className }: { readonly kind: SourceKind; readonly className?: string }) {
  const isDemo = kind === "DEMO_SYNTHETIC";
  return (
    <span
      className={[
        "inline-flex items-center gap-1.5 rounded border px-1.5 py-0.5 text-[0.6875rem] font-bold uppercase tracking-wide",
        isDemo
          ? "border-amber-500/60 bg-amber-500/10 text-amber-700 dark:text-amber-300"
          : "border-line bg-surface-sunken text-ink-muted",
        className ?? "",
      ].join(" ")}
      title={SOURCE_TITLE[kind]}
      data-source={kind}
    >
      {SOURCE_LABEL[kind]}
    </span>
  );
}

/** Marks scripted (non-model) AI output. Required wherever `DEMO_AI` applies. */
export function DemoAiBadge({ className }: { readonly className?: string }) {
  return (
    <span
      className={[
        "inline-flex items-center gap-1.5 rounded border border-violet-500/60 bg-violet-500/10 px-1.5 py-0.5",
        "text-[0.6875rem] font-bold uppercase tracking-wide text-violet-700 dark:text-violet-300",
        className ?? "",
      ].join(" ")}
      title="Scripted demo response, not generated by a live AI model."
      data-source="DEMO_AI"
    >
      DEMO AI
    </span>
  );
}

/**
 * Stale-source banner. Shown when the backend reports `source.is_stale`, so a
 * user is told the data may be out of date rather than being shown a confident
 * but outdated score.
 */
export function StaleSourceBanner({
  lastSyncedAt,
  className,
}: {
  readonly lastSyncedAt: string | null;
  readonly className?: string;
}) {
  const synced = formatKickoff(lastSyncedAt);
  return (
    <p
      role="status"
      className={[
        "flex flex-wrap items-center gap-x-2 gap-y-1 rounded-md border border-amber-500/50 bg-amber-500/10",
        "px-3 py-2 text-sm text-amber-800 dark:text-amber-200",
        className ?? "",
      ].join(" ")}
    >
      <strong className="font-semibold">Source may be out of date.</strong>
      {synced ? (
        <span>
          Last synced <time dateTime={machineDateTime(lastSyncedAt)}>{synced}</time>.
        </span>
      ) : (
        <span>This feed has never reported a successful sync.</span>
      )}
    </p>
  );
}
